"""Builds the sample shops: photos in public/samples/ and the SQL to add or
remove them in supabase/seed/.

    python3 scripts/samples/build.py

Run the SQL in the Supabase SQL editor. Re-running the add script is safe.
"""

import uuid
from pathlib import Path

import draw
from data import SAMPLE_EMAIL_DOMAIN, SHOPS

ROOT = Path(__file__).resolve().parents[2]
PHOTOS = ROOT / "public" / "samples"
SEED = ROOT / "supabase" / "seed"
NAMESPACE = uuid.UUID("6f1c4a52-3d0b-4c8e-9a51-5a3e0d0c0de5")

REQUIRED_PHOTOS = ("front", "back", "label")


def uid(*parts):
    return str(uuid.uuid5(NAMESPACE, "/".join(parts)))


def q(value):
    if value is None:
        return "null"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def arr(values):
    return "array[" + ", ".join(q(v) for v in values) + "]::text[]"


def photos_for(shop, index, item):
    kinds = list(REQUIRED_PHOTOS) + (["flaw"] if item.get("flaws") else [])
    return {kind: f"samples/{shop['slug']}/{index + 1}-{kind}.webp" for kind in kinds}


def build_photos():
    for si, shop in enumerate(SHOPS):
        for ii, item in enumerate(shop["items"]):
            seed = si * 100 + ii
            for kind, rel in photos_for(shop, ii, item).items():
                if kind in ("front", "back"):
                    img = draw.garment_photo(item["art"], kind, seed)
                elif kind == "label":
                    img = draw.label_photo(item["art"], item["brand"], item["size"], seed)
                else:
                    img = draw.flaw_photo(item["art"], item["flaws"], seed)
                draw.save(img, ROOT / "public" / rel)


def add_sql():
    out = [
        "-- Sample shops for demos. Generated by scripts/samples/build.py; do not edit by hand.",
        "-- Safe to run more than once. Remove everything with remove-sample-shops.sql.",
        "begin;",
        "",
    ]
    hour = 0
    for si, shop in enumerate(SHOPS):
        owner = uid("owner", shop["slug"])
        shop_id = uid("shop", shop["slug"])
        email = f"{shop['slug']}@{SAMPLE_EMAIL_DOMAIN}"
        out += [
            f"-- {shop['name']}",
            "insert into auth.users (id, instance_id, aud, role, email, encrypted_password, email_confirmed_at,",
            "  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,",
            "  confirmation_token, recovery_token, email_change_token_new, email_change)",
            f"values ({q(owner)}, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', {q(email)}, '', now(),",
            "  '{\"provider\":\"email\",\"providers\":[\"email\"],\"sample\":true}', '{}', now(), now(), '', '', '', '')",
            "on conflict (id) do nothing;",
            "insert into public.shops (id, owner_id, slug, display_name, province, bio, social_links, status, approved_at)",
            f"values ({q(shop_id)}, {q(owner)}, {q(shop['slug'])}, {q(shop['name'])}, {q(shop['province'])}, {q(shop['bio'])},",
            f"  {arr(shop['social'])}, 'approved', now() - interval '{si} days')",
            "on conflict (id) do nothing;",
        ]
        for style in shop["styles"]:
            out.append(
                f"insert into public.shop_styles (shop_id, style_id) select {q(shop_id)}, id from public.styles "
                f"where slug = {q(style)} on conflict do nothing;"
            )
        for ii, item in enumerate(shop["items"]):
            pid = uid("item", shop["slug"], str(ii))
            m = item["m"]
            hour += 7
            out += [
                "insert into public.products (id, shop_id, title, brand, description, category, size_label, price_satang,",
                "  condition, has_flaws, flaws_note, chest_cm, length_cm, shoulder_cm, waist_cm, created_at)",
                f"values ({q(pid)}, {q(shop_id)}, {q(item['title'])}, {q(item['brand'])}, 'สินค้าตัวอย่าง ไม่ได้วางขายจริง',",
                f"  {q(item['category'])}, {q(item['size'])}, {item['price'] * 100}, {q(item['condition'])},",
                f"  {'true' if item.get('flaws') else 'false'}, {q(item.get('flaws'))},",
                f"  {q(m.get('chest'))}, {q(m.get('length'))}, {q(m.get('shoulder'))}, {q(m.get('waist'))},",
                f"  now() - interval '{hour} hours')",
                "on conflict (id) do nothing;",
            ]
            for style in item["styles"]:
                out.append(
                    f"insert into public.product_styles (product_id, style_id) select {q(pid)}, id from public.styles "
                    f"where slug = {q(style)} on conflict do nothing;"
                )
            for kind, path in photos_for(shop, ii, item).items():
                out.append(
                    f"insert into public.product_images (product_id, kind, storage_path) select {q(pid)}, {q(kind)}, {q(path)} "
                    f"where not exists (select 1 from public.product_images where product_id = {q(pid)} and kind = {q(kind)});"
                )
            out.append(f"update public.products set status = 'active' where id = {q(pid)} and status = 'draft';")
            status = item.get("status")
            if status == "sold":
                out.append(f"update public.products set status = 'sold', sold_at = now() where id = {q(pid)} and status = 'active';")
            elif status == "reserved":
                out.append(f"update public.products set status = 'reserved' where id = {q(pid)} and status = 'active';")
        out.append("")
    out += ["commit;", ""]
    return "\n".join(out)


def remove_sql():
    shops = "select id from public.shops where owner_id in (select id from auth.users where email like '%@" + SAMPLE_EMAIL_DOMAIN + "')"
    return "\n".join([
        "-- Removes every sample shop, item, photo row and owner account added by sample-shops.sql.",
        "-- Generated by scripts/samples/build.py. Real shops are untouched.",
        "begin;",
        f"delete from public.reports where shop_id in ({shops})",
        f"  or product_id in (select id from public.products where shop_id in ({shops}));",
        f"delete from public.products where shop_id in ({shops});",
        f"delete from auth.users where email like '%@{SAMPLE_EMAIL_DOMAIN}';",
        "commit;",
        "",
    ])


if __name__ == "__main__":
    SEED.mkdir(parents=True, exist_ok=True)
    (SEED / "sample-shops.sql").write_text(add_sql())
    (SEED / "remove-sample-shops.sql").write_text(remove_sql())
    build_photos()
    count = sum(1 for _ in PHOTOS.rglob("*.webp"))
    size = sum(p.stat().st_size for p in PHOTOS.rglob("*.webp"))
    print(f"{count} photos, {size / 1e6:.1f} MB")
