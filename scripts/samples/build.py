"""Builds the sample shops: photos in public/samples/ and the SQL to add or
remove them in supabase/seed/.

    python3 scripts/samples/build.py

Run the SQL in the Supabase SQL editor. Re-running the add script is safe.
"""

import json
import uuid
from pathlib import Path

import draw
from data import SAMPLE_EMAIL_DOMAIN, SHOPS

ROOT = Path(__file__).resolve().parents[2]
PHOTOS = ROOT / "public" / "samples"
SEED = ROOT / "supabase" / "seed"
NAMESPACE = uuid.UUID("6f1c4a52-3d0b-4c8e-9a51-5a3e0d0c0de5")

REQUIRED_PHOTOS = ("front", "back", "label")


def uid(*parts):
    return str(uuid.uuid5(NAMESPACE, "/".join(parts)))


def photos_for(shop, index, item):
    kinds = list(REQUIRED_PHOTOS) + (["flaw"] if item.get("flaws") else [])
    return {kind: f"samples/{shop['slug']}/{index + 1}-{kind}.webp" for kind in kinds}


def build_photos():
    for si, shop in enumerate(SHOPS):
        for ii, item in enumerate(shop["items"]):
            seed = si * 100 + ii
            for kind, rel in photos_for(shop, ii, item).items():
                if kind in ("front", "back"):
                    img = draw.garment_photo(item["art"], kind, seed)
                elif kind == "label":
                    img = draw.label_photo(item["art"], item["brand"], item["size"], seed)
                else:
                    img = draw.flaw_photo(item["art"], item["flaws"], seed)
                draw.save(img, ROOT / "public" / rel)


def add_sql():
    """Compact form: the data as JSON plus one loop, small enough to paste into the SQL editor."""
    shops = []
    hour = 0
    for si, shop in enumerate(SHOPS):
        items = []
        for ii, item in enumerate(shop["items"]):
            hour += 7
            items.append({
                "id": uid("item", shop["slug"], str(ii)),
                "n": ii + 1,
                "title": item["title"],
                "brand": item["brand"],
                "category": item["category"],
                "size": item["size"],
                "price": item["price"],
                "condition": item["condition"],
                "flaws": item.get("flaws"),
                **{k: v for k, v in item["m"].items()},
                "styles": item["styles"],
                "kinds": list(photos_for(shop, ii, item)),
                "status": item.get("status", "active"),
                "age_hours": hour,
            })
        shops.append({
            "id": uid("shop", shop["slug"]),
            "owner": uid("owner", shop["slug"]),
            "email": f"{shop['slug']}@{SAMPLE_EMAIL_DOMAIN}",
            "slug": shop["slug"],
            "name": shop["name"],
            "province": shop["province"],
            "bio": shop["bio"],
            "social": shop["social"],
            "styles": shop["styles"],
            "age_days": si,
            "items": items,
        })
    data = json.dumps(shops, ensure_ascii=False, separators=(",", ":"))
    assert "$json$" not in data
    return SQL_TEMPLATE.replace("__DATA__", data)


SQL_TEMPLATE = """-- Sample shops for demos. Generated by scripts/samples/build.py; do not edit by hand.
-- Safe to run more than once. Remove everything with remove-sample-shops.sql.
begin;
do $$
declare
  s jsonb;
  it jsonb;
  pid uuid;
begin
  for s in select * from jsonb_array_elements($json$__DATA__$json$::jsonb) loop
    insert into auth.users (id, instance_id, aud, role, email, encrypted_password, email_confirmed_at,
      raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
      confirmation_token, recovery_token, email_change_token_new, email_change)
    values ((s->>'owner')::uuid, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated',
      s->>'email', '', now(), '{"provider":"email","providers":["email"],"sample":true}', '{}', now(), now(), '', '', '', '')
    on conflict (id) do nothing;

    insert into public.shops (id, owner_id, slug, display_name, province, bio, social_links, status, approved_at)
    values ((s->>'id')::uuid, (s->>'owner')::uuid, s->>'slug', s->>'name', s->>'province', s->>'bio',
      array(select jsonb_array_elements_text(s->'social')), 'approved',
      now() - make_interval(days => (s->>'age_days')::int))
    on conflict (id) do nothing;

    insert into public.shop_styles (shop_id, style_id)
    select (s->>'id')::uuid, st.id from public.styles st
    where st.slug in (select jsonb_array_elements_text(s->'styles'))
    on conflict do nothing;

    for it in select * from jsonb_array_elements(s->'items') loop
      pid := (it->>'id')::uuid;
      insert into public.products (id, shop_id, title, brand, description, category, size_label, price_satang,
        condition, has_flaws, flaws_note, chest_cm, length_cm, shoulder_cm, waist_cm, created_at)
      values (pid, (s->>'id')::uuid, it->>'title', it->>'brand', 'สินค้าตัวอย่าง ไม่ได้วางขายจริง',
        (it->>'category')::public.product_category, it->>'size', (it->>'price')::int * 100,
        (it->>'condition')::public.product_condition, it->>'flaws' is not null, it->>'flaws',
        (it->>'chest')::numeric, (it->>'length')::numeric, (it->>'shoulder')::numeric, (it->>'waist')::numeric,
        now() - make_interval(hours => (it->>'age_hours')::int))
      on conflict (id) do nothing;

      insert into public.product_styles (product_id, style_id)
      select pid, st.id from public.styles st
      where st.slug in (select jsonb_array_elements_text(it->'styles'))
      on conflict do nothing;

      insert into public.product_images (product_id, kind, storage_path)
      select pid, k::public.image_kind, 'samples/' || (s->>'slug') || '/' || (it->>'n') || '-' || k || '.webp'
      from jsonb_array_elements_text(it->'kinds') as k
      where not exists (select 1 from public.product_images i where i.product_id = pid and i.kind = k::public.image_kind);

      update public.products set status = 'active' where id = pid and status = 'draft';
      if it->>'status' = 'sold' then
        update public.products set status = 'sold', sold_at = now() where id = pid and status = 'active';
      elsif it->>'status' = 'reserved' then
        update public.products set status = 'reserved' where id = pid and status = 'active';
      end if;
    end loop;
  end loop;
end
$$;
commit;
"""


def remove_sql():
    shops = "select id from public.shops where owner_id in (select id from auth.users where email like '%@" + SAMPLE_EMAIL_DOMAIN + "')"
    return "\n".join([
        "-- Removes every sample shop, item, photo row and owner account added by sample-shops.sql.",
        "-- Generated by scripts/samples/build.py. Real shops are untouched.",
        "begin;",
        f"delete from public.reports where shop_id in ({shops})",
        f"  or product_id in (select id from public.products where shop_id in ({shops}));",
        f"delete from public.products where shop_id in ({shops});",
        f"delete from auth.users where email like '%@{SAMPLE_EMAIL_DOMAIN}';",
        "commit;",
        "",
    ])


if __name__ == "__main__":
    SEED.mkdir(parents=True, exist_ok=True)
    (SEED / "sample-shops.sql").write_text(add_sql())
    (SEED / "remove-sample-shops.sql").write_text(remove_sql())
    build_photos()
    count = sum(1 for _ in PHOTOS.rglob("*.webp"))
    size = sum(p.stat().st_size for p in PHOTOS.rglob("*.webp"))
    print(f"{count} photos, {size / 1e6:.1f} MB")
